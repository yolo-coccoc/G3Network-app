"""Write js/features.js: a snapshot of the portal features in the feature catalog.

The prototype's coverage page and the feature chips on every screen read this
snapshot, so they show the catalog's names and build status without a server.
Re-run it after the catalog changes:

    cd backend && uv run python ../web_portal_prototype/feature_snapshot.py
"""

import json
from datetime import date
from pathlib import Path

import yaml

PROTOTYPE_DIR = Path(__file__).resolve().parent
CATALOG_PATH = PROTOTYPE_DIR.parent / "docs/product/features/features.yaml"
OUTPUT_PATH = PROTOTYPE_DIR / "js/features.js"


def main() -> None:
    """Read the catalog and write the portal features as a JavaScript global."""
    catalog = yaml.safe_load(CATALOG_PATH.read_text(encoding="utf-8"))
    domains = {
        domain["prefix"]: [domain["name"], domain["name_vi"]]
        for domain in catalog["domains"]
    }
    portal_features = [
        {
            "code": feature["code"],
            "name": feature["name"],
            "name_vi": feature["name_vi"],
            "what": " ".join(feature["what"].split()),
            "users": feature["users"],
            "priority": feature["priority"],
            "release": feature["release"],
            "backend": feature["surfaces"].get("backend", "-"),
            "portal": feature["surfaces"]["portal"],
        }
        for feature in catalog["features"]
        if "portal" in feature.get("surfaces", {})
    ]
    snapshot = {
        "taken_on": date.today().isoformat(),
        "domains": domains,
        "features": portal_features,
    }
    OUTPUT_PATH.write_text(
        "// GENERATED by feature_snapshot.py from docs/product/features/features.yaml."
        " Do not edit by hand.\n"
        f"window.G3_FEATURES = {json.dumps(snapshot, ensure_ascii=False, indent=1)};\n",
        encoding="utf-8",
    )
    print(f"{len(portal_features)} portal features -> {OUTPUT_PATH}")


if __name__ == "__main__":
    main()
